# ================================================================
# ALLOWED FILE TYPES
# ================================================================

ALLOWED_EXTENSIONS = {
    "png",
    "jpg",
    "jpeg",
    "bmp",
    "tif",
    "tiff",
}


def allowed_file(filename):
    """Return True when the filename has a supported image extension."""
    if not filename or "." not in filename:
        return False

    extension = filename.rsplit(".", 1)[1].lower()
    return extension in ALLOWED_EXTENSIONS


# ================================================================
# CORS
# ================================================================
#
# GitHub Pages is a different origin from Render.
# The frontend sends multipart/form-data to /analyze, so the API
# explicitly allows cross-origin requests.
#
# CORS headers are also applied to error responses generated by Flask.
# ================================================================

@app.after_request
def add_cors_headers(response):
    response.headers["Access-Control-Allow-Origin"] = "*"
    response.headers["Access-Control-Allow-Methods"] = "GET, POST, OPTIONS"
    response.headers["Access-Control-Allow-Headers"] = "Content-Type"
    response.headers["Access-Control-Expose-Headers"] = "Content-Type"
    return response


