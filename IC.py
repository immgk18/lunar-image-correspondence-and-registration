@app.route("/analyze", methods=["POST"])
def analyze():
    """
    Receive two lunar images and run the AI registration pipeline.

    IMPORTANT:
    The heavy lunar_backend import happens INSIDE this function.
    This keeps Gunicorn/Flask startup lightweight and prevents the
    PyTorch/LoFTR stack from being loaded merely by starting the web
    server.
    """

    request_id = uuid.uuid4().hex[:8]

    image_A_path = None
    image_B_path = None

    print("\n" + "=" * 70)
    print("NEW LUNAR ANALYSIS REQUEST")
    print("Request ID:", request_id)
    print("=" * 70)

    try:
        # ------------------------------------------------------------
        # CHECK IMAGE A
        # ------------------------------------------------------------

        if "image_A" not in request.files:
            return jsonify({
                "success": False,
                "request_id": request_id,
                "error": "Reference Image A was not uploaded.",
            }), 400

        # ------------------------------------------------------------
        # CHECK IMAGE B
        # ------------------------------------------------------------

        if "image_B" not in request.files:
            return jsonify({
                "success": False,
                "request_id": request_id,
                "error": "Target Image B was not uploaded.",
            }), 400

        image_A = request.files["image_A"]
        image_B = request.files["image_B"]

        # ------------------------------------------------------------
        # CHECK FILENAMES
        # ------------------------------------------------------------

        if not image_A.filename:
            return jsonify({
                "success": False,
                "request_id": request_id,
                "error": "Image A has no filename.",
            }), 400

        if not image_B.filename:
            return jsonify({
                "success": False,
                "request_id": request_id,
                "error": "Image B has no filename.",
            }), 400

        # ------------------------------------------------------------
        # CHECK FILE TYPES
        # ------------------------------------------------------------

        if not allowed_file(image_A.filename):
            return jsonify({
                "success": False,
                "request_id": request_id,
                "error": "Unsupported Image A format.",
            }), 400

        if not allowed_file(image_B.filename):
            return jsonify({
                "success": False,
                "request_id": request_id,
                "error": "Unsupported Image B format.",
            }), 400

        # ------------------------------------------------------------
        # SANITIZE EXTENSIONS
        # ------------------------------------------------------------

        extension_A = Path(image_A.filename).suffix.lower()
        extension_B = Path(image_B.filename).suffix.lower()

        # The extension has already been checked against the allowlist.
        # UUID names prevent collisions and unsafe user-controlled paths.
        image_A_path = UPLOAD_FOLDER / f"image_A_{request_id}{extension_A}"
        image_B_path = UPLOAD_FOLDER / f"image_B_{request_id}{extension_B}"

        # ------------------------------------------------------------
        # SAVE UPLOADS
        # ------------------------------------------------------------

        image_A.save(str(image_A_path))
        image_B.save(str(image_B_path))

        print("Image A received:", image_A_path)
        print("Image B received:", image_B_path)

        # ------------------------------------------------------------
        # LAZY IMPORT OF HEAVY AI BACKEND
        # ------------------------------------------------------------
        #
        # DO NOT move this import to the top of this file.
        # PyTorch/Kornia/LoFTR should not be loaded during Gunicorn
        # startup.
        # ------------------------------------------------------------

        print("Loading AI backend...")

        from lunar_backend import analyze_lunar_images

        print("Starting AI processing...")

        # ------------------------------------------------------------
        # RUN AI PIPELINE
        # ------------------------------------------------------------

        results = analyze_lunar_images(
            str(image_A_path),
            str(image_B_path),
            output_folder=str(RESULTS_FOLDER),
        )

        # ------------------------------------------------------------
        # RESULT IMAGE URLS
        # ------------------------------------------------------------

        results["images"] = {
            "preprocessed_A": "/results/preprocessed_A.png",
            "preprocessed_B": "/results/preprocessed_B.png",
            "ransac_inliers": "/results/ransac_inliers.png",
            "registered_refined": "/results/registered_refined.png",
            "correspondence_quality_map":
                "/results/correspondence_quality_map.png",
            "spatial_distribution":
                "/results/spatial_distribution.png",
        }

        # ------------------------------------------------------------
        # FINAL RESPONSE
        # ------------------------------------------------------------

        response = {
            "success": True,
            "message": "Lunar image analysis completed successfully.",
            "request_id": request_id,
            "results": results,
        }

        print("AI analysis completed.")
        print("Results sent to frontend.")
        print("=" * 70)

        return jsonify(response), 200

    except MemoryError:
        # Python-level MemoryError. Note that an OS-level OOM kill can
        # terminate the whole process before Flask can reach this block.
        print("ERROR: Python reported insufficient memory.")

        return jsonify({
            "success": False,
            "request_id": request_id,
            "error": (
                "The AI analysis requires more memory than the server "
                "currently has available."
            ),
        }), 503

    except Exception as exc:
        print("ERROR during analysis:", repr(exc))

        return jsonify({
            "success": False,
            "request_id": request_id,
            "error": str(exc),
        }), 500

    finally:
        # Uploaded source files are temporary inputs. Remove them after
        # processing so repeated requests do not fill the Render disk.
        for uploaded_path in (image_A_path, image_B_path):
            if uploaded_path is not None:
                try:
                    Path(uploaded_path).unlink(missing_ok=True)
                except Exception as cleanup_error:
                    print(
                        "Warning: could not remove temporary upload:",
                        cleanup_error,
                    )


